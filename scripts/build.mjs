#!/usr/bin/env node
// Builds every figure file in a folder into one stroke file for the canvas player.
// Each .mjs file default-exports an array of figure(...) results.
// Usage: node build.mjs <figures-dir> <out.js>
import { readdir, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const [dir, out] = process.argv.slice(2);
if (!dir || !out) { console.error("usage: build.mjs <figures-dir> <out.js>"); process.exit(1); }

const files = (await readdir(dir)).filter((f) => f.endsWith(".mjs")).sort();
const modules = await Promise.all(files.map((f) => import(pathToFileURL(resolve(join(dir, f))).href)));
const figures = modules.flatMap((m) => m.default);

const body = figures.map(([name, data]) => `window.${name} = ${JSON.stringify(data)};`).join("\n");
await writeFile(out, `// GENERATED by article-drawings/scripts/build.mjs. Change the figure files and re-run it.\n${body}\n`);
console.log(`Drew ${figures.length} figures from ${files.length} files → ${out}`);
